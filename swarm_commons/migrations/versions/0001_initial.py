    if op.get_bind().dialect.name == "postgresql":
        schema = re.sub(r"\bid INTEGER PRIMARY KEY", "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", schema)
    for sql in schema.split(";"):
        if sql.strip():
            op.execute(sql)


